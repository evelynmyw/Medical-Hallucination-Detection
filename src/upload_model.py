"""Upload one trained seed to the Hugging Face Hub, with its threshold and a model card.

Usage (from repo root, after `huggingface_hub.login()`):
    python -m src.upload_model \
        --seed-dir /content/drive/MyDrive/medhallu/bio_clinicalbert/seed44 \
        --repo-id <hf-username>/medhallu-bio-clinicalbert
"""

import argparse
import json
import shutil
import tempfile
from pathlib import Path

import pandas as pd
from huggingface_hub import HfApi
from transformers import AutoConfig

GITHUB_URL = "https://github.com/evelynmyw/Medical-Hallucination-Detection"
ID2LABEL = {0: "ground_truth", 1: "hallucinated"}

USAGE = '''```python
import json
import torch
from huggingface_hub import hf_hub_download
from transformers import AutoModelForSequenceClassification, AutoTokenizer

repo = "REPO_ID"
tokenizer = AutoTokenizer.from_pretrained(repo)
model = AutoModelForSequenceClassification.from_pretrained(repo).eval()
threshold = json.load(open(hf_hub_download(repo, "threshold.json")))["threshold"]

question = "Does X reduce Y in patients with Z?"
answer = "X significantly reduces Y ..."
inputs = tokenizer(question, answer, truncation=True, max_length=256, return_tensors="pt")
with torch.no_grad():
    p_hallucinated = torch.softmax(model(**inputs).logits, dim=-1)[0, 1].item()

print(p_hallucinated, "hallucinated" if p_hallucinated >= threshold else "ground_truth")
```'''


def model_card(repo_id: str, seed: str, threshold: float, results: pd.DataFrame) -> str:
    m = results.loc[f"bert_{seed}"]
    mean, std = results.loc["bert_mean"], results.loc["bert_std"]
    tfidf = results.loc["tfidf_answer"]
    row = lambda name, key: (f"| {name} | {m[key]:.3f} | {mean[key]:.3f} ± {std[key]:.3f} "
                             f"| {tfidf[key]:.3f} |")
    return f"""---
language: en
base_model: emilyalsentzer/Bio_ClinicalBERT
datasets:
- UTAustin-AIHealth/MedHallu
pipeline_tag: text-classification
tags:
- medical
- hallucination-detection
---

# MedHallu hallucination detector (Bio_ClinicalBERT)

Binary classifier: given a medical question and a candidate answer, predicts whether the
answer is **hallucinated** (label 1) or the **ground truth** (label 0). Fine-tuned from
`emilyalsentzer/Bio_ClinicalBERT` on the MedHallu dataset (training seed {seed.removeprefix("seed")}).

Code, data split, and full analysis: {GITHUB_URL}

## Decision threshold

Use the threshold in `threshold.json` (**{threshold:.2f}**, chosen on the validation set),
not argmax / 0.5:

{USAGE.replace("REPO_ID", repo_id)}

## Training data

- Train / validation: `pqa_artificial` (9,000 questions), split by question 85/15, so the two
  answers of a question are never in different splits.
- Test: `pqa_labeled` (1,000 questions, 2,000 samples), no question overlap with training data.
- Input: `[CLS] question [SEP] answer [SEP]`, max 256 tokens. The `Knowledge` passages are not used.

## Test results (`pqa_labeled`)

| Metric | This model | Mean ± std over 3 seeds | TF-IDF + LR baseline |
|---|---|---|---|
{row("Accuracy", "accuracy")}
{row("Precision", "precision")}
{row("Recall", "recall")}
{row("F1", "f1")}
{row("AUC", "auc")}
{row("Accuracy, length-matched pairs", "acc_len_matched")}

This seed has the highest test accuracy of the three; the mean ± std is the fairer estimate.

## Limitations

- **Style shortcut.** In MedHallu, hallucinated answers differ from the ground truth in length
  and wording (ground truth hedges with *may / could*; hallucinations make confident causal
  claims). A TF-IDF baseline on the answer alone reaches 0.90 test accuracy. The model partly
  relies on these cues: it tends to miss hallucinations written in cautious language and to
  flag short, assertive correct answers.
- **No fact checking.** The model sees only the question and the answer. Hallucinations that
  change a single fact (e.g. "above" vs "below") are often missed.
- **Errors are mostly missed hallucinations** (recall < precision).
- Trained on PubMedQA-derived questions with hallucinations generated by one pipeline; it may not
  transfer to other sources of hallucinations.

**Not intended for clinical use.** This is a research / learning project.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed-dir", required=True, help="seedXX dir with best/ and threshold.json")
    parser.add_argument("--repo-id", required=True, help="<hf-username>/<model-name>")
    parser.add_argument("--results-csv", default="results/bio_clinicalbert/test_results.csv")
    parser.add_argument("--private", action="store_true")
    args = parser.parse_args()

    seed_dir = Path(args.seed_dir)
    threshold = json.loads((seed_dir / "threshold.json").read_text())["threshold"]
    results = pd.read_csv(args.results_csv, index_col=0)

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        shutil.copytree(seed_dir / "best", tmp, dirs_exist_ok=True)
        shutil.copy(seed_dir / "threshold.json", tmp)

        config = AutoConfig.from_pretrained(tmp)
        config.id2label = ID2LABEL
        config.label2id = {v: k for k, v in ID2LABEL.items()}
        config.save_pretrained(tmp)

        (tmp / "README.md").write_text(model_card(args.repo_id, seed_dir.name, threshold, results))
        print("Uploading:", sorted(p.name for p in tmp.iterdir()))

        api = HfApi()
        api.create_repo(args.repo_id, private=args.private, exist_ok=True)
        api.upload_folder(folder_path=tmp, repo_id=args.repo_id,
                          commit_message=f"Upload {seed_dir.name} with threshold and model card")

    print(f"Done: https://huggingface.co/{args.repo_id}")


if __name__ == "__main__":
    main()
